"""
generate_insights.py
---------------------
Automatically computes the final business insights report from the
cleaned + risk-scored datasets. Every number in the report is computed
from the actual generated data - nothing is invented or hardcoded.

Inputs:
    data/processed/banking_transactions_cleaned.csv
    data/processed/risk_transactions.csv
    data/processed/customer_risk_profile.csv

Output:
    outputs/insights/final_insights_report.md
"""

import os
import pandas as pd

BASE_DIR = os.path.join(os.path.dirname(__file__), "..")
CLEANED_PATH = os.path.join(BASE_DIR, "data", "processed", "banking_transactions_cleaned.csv")
RISK_TXN_PATH = os.path.join(BASE_DIR, "data", "processed", "risk_transactions.csv")
RISK_CUST_PATH = os.path.join(BASE_DIR, "data", "processed", "customer_risk_profile.csv")
REPORT_PATH = os.path.join(BASE_DIR, "outputs", "insights", "final_insights_report.md")


def pct(n, d):
    return f"{n / d * 100:.2f}%"


def main():
    df = pd.read_csv(CLEANED_PATH)
    risk = pd.read_csv(RISK_TXN_PATH)
    cust = pd.read_csv(RISK_CUST_PATH)
    df["transaction_date"] = pd.to_datetime(df["transaction_date"])

    # ------------------- TRANSACTION INSIGHTS --------------------------
    total_txns = len(df)
    total_value = df["amount"].sum()
    avg_value = df["amount"].mean()
    success = (df["transaction_status"] == "Success").sum()
    failed = (df["transaction_status"] == "Failed").sum()
    pending = (df["transaction_status"] == "Pending").sum()
    success_rate = success / total_txns * 100

    # ------------------- CUSTOMER INSIGHTS ------------------------------
    n_customers = df["customer_id"].nunique()
    n_accounts = df["account_id"].nunique()
    avg_txns_per_cust = df.groupby("customer_id")["transaction_id"].count().mean()
    avg_value_per_cust = df.groupby("customer_id")["amount"].sum().mean()
    top5_cust = (df.groupby("customer_id")["amount"].sum()
                   .sort_values(ascending=False).head(5))
    busiest_hour = df["transaction_hour"].value_counts().idxmax()

    # ------------------- CHANNEL INSIGHTS -------------------------------
    ch = df.groupby("channel").agg(
        txns=("transaction_id", "count"),
        value=("amount", "sum"),
        failures=("transaction_status", lambda s: (s == "Failed").sum()),
    ).sort_values("txns", ascending=False)
    ch["failure_rate_pct"] = (ch["failures"] / ch["txns"] * 100).round(2)

    # ------------------- PAYMENT INSIGHTS -------------------------------
    pm = df.groupby("payment_method").agg(
        txns=("transaction_id", "count"),
        value=("amount", "sum"),
        failures=("transaction_status", lambda s: (s == "Failed").sum()),
    ).sort_values("txns", ascending=False)
    pm["failure_rate_pct"] = (pm["failures"] / pm["txns"] * 100).round(2)

    # ------------------- GEOGRAPHIC INSIGHTS ----------------------------
    top_cities = df.groupby("city")["amount"].sum().sort_values(ascending=False).head(5)
    top_branches = df.groupby("branch")["amount"].sum().sort_values(ascending=False).head(5)
    top_states = df.groupby("state")["amount"].sum().sort_values(ascending=False).head(5)

    # ------------------- RISK INSIGHTS ----------------------------------
    high_risk = risk[risk["risk_level"] == "HIGH"]
    medium_risk = risk[risk["risk_level"] == "MEDIUM"]
    intl_high = high_risk["is_international"].sum()
    n_cust_high_risk = high_risk["customer_id"].nunique()

    rule_cols = ["is_high_amount", "has_multiple_failures", "is_unusual_international",
                 "is_rapid_consecutive", "is_high_daily_activity", "above_customer_avg"]
    rule_names = {
        "is_high_amount": "Amount > 5x customer's own average (Rule 1)",
        "has_multiple_failures": "Failed txn by customer with >=3 total failures (Rule 2)",
        "is_unusual_international": "International txn > 3x customer average (Rule 3)",
        "is_rapid_consecutive": "Amount > 2x customer's previous txn (Rule 4)",
        "is_high_daily_activity": ">=5 txns by one customer on one day (Rule 5)",
        "above_customer_avg": "Amount > 2x customer's own average (Rule 6)",
    }
    rule_hits = risk[rule_cols].sum().sort_values(ascending=False)

    lines = []
    add = lines.append

    add("# Banking Transaction Data Pipeline - Final Insights Report")
    add("")
    add("All figures below are computed automatically from the synthetic")
    add("datasets generated by this project (see `python/generate_insights.py`).")
    add("")
    add("## Transaction Insights")
    add("")
    add(f"- Total transactions: **{total_txns:,}**")
    add(f"- Total transaction value: **INR {total_value:,.2f}**")
    add(f"- Average transaction value: **INR {avg_value:,.2f}**")
    add(f"- Successful: {success:,} | Failed: {failed:,} | Pending: {pending:,}")
    add(f"- Transaction success rate: **{success_rate:.2f}%**")
    add("")
    add("## Customer Insights")
    add("")
    add(f"- Unique customers: **{n_customers:,}** across {n_accounts:,} accounts")
    add(f"- Average transactions per customer: {avg_txns_per_cust:.1f}")
    add(f"- Average lifetime transaction value per customer: INR {avg_value_per_cust:,.2f}")
    add(f"- Busiest transaction hour of the day: **{busiest_hour}:00**")
    add("- Top 5 customers by total transaction value:")
    for cid, v in top5_cust.items():
        add(f"  - {cid}: INR {v:,.2f}")
    add("")
    add("## Channel Insights")
    add("")
    add("| Channel | Transactions | Total Value (INR) | Failure Rate |")
    add("|---------|--------------|-------------------|--------------|")
    for name, row in ch.iterrows():
        add(f"| {name} | {row['txns']:,} | {row['value']:,.2f} | {row['failure_rate_pct']:.2f}% |")
    add("")
    add(f"- Most-used channel: **{ch.index[0]}** ({ch['txns'].iloc[0]:,} transactions)")
    add(f"- Highest-failure channel: **{ch['failure_rate_pct'].idxmax()}** "
        f"({ch['failure_rate_pct'].max():.2f}% failure rate)")
    add("")
    add("## Payment Method Insights")
    add("")
    add("| Payment Method | Transactions | Total Value (INR) | Failure Rate |")
    add("|----------------|--------------|-------------------|--------------|")
    for name, row in pm.iterrows():
        add(f"| {name} | {row['txns']:,} | {row['value']:,.2f} | {row['failure_rate_pct']:.2f}% |")
    add("")
    add(f"- Most-used payment method: **{pm.index[0]}** ({pm['txns'].iloc[0]:,} transactions)")
    add("")
    add("## Geographic Insights")
    add("")
    add("- Top 5 cities by total transaction value:")
    for c, v in top_cities.items():
        add(f"  - {c}: INR {v:,.2f}")
    add("- Top 5 branches by total transaction value:")
    for b, v in top_branches.items():
        add(f"  - {b}: INR {v:,.2f}")
    add("- Top 5 states by total transaction value:")
    for s, v in top_states.items():
        add(f"  - {s}: INR {v:,.2f}")
    add("")
    add("## Risk Insights")
    add("")
    add("*Rule-based analytical indicators on synthetic data - not confirmed fraud.*")
    add("")
    add(f"- HIGH-risk transactions: **{len(high_risk):,}** ({pct(len(high_risk), total_txns)} of all transactions)")
    add(f"- MEDIUM-risk transactions: {len(medium_risk):,} ({pct(len(medium_risk), total_txns)})")
    add(f"- Customers with at least one HIGH-risk transaction: {n_cust_high_risk:,}")
    add(f"- HIGH-risk transactions that were international: {intl_high:,}")
    add("- Risk rule trigger counts (most common indicators):")
    for col, hits in rule_hits.items():
        add(f"  - {rule_names[col]}: {hits:,} transactions")
    add("")
    add("---")
    add("Generated automatically by `python/generate_insights.py` - "
        "do not edit manually.")

    os.makedirs(os.path.dirname(REPORT_PATH), exist_ok=True)
    with open(REPORT_PATH, "w") as f:
        f.write("\n".join(lines) + "\n")

    print("\n".join(lines[:20]))
    print("...")
    print(f"\nSaved -> {REPORT_PATH}")


if __name__ == "__main__":
    main()
